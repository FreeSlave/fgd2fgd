#include "Fgd.h"
#include "util.h"
#include <cstdio>
#include <iostream>

enum class EditorType
{
    Hammer,
    TrenchBroom,
    NetRadiant
};

const char* fgdClassTypeToString(int classType)
{
    switch(classType)
    {
        case FGD_CLASS_BASE:
            return "@BaseClass";
        case FGD_CLASS_SOLID:
            return "@SolidClass";
        default:
            return "@PointClass";
    }
}

bool isKnownTypeForAllEditors(const char* keyType)
{
    static const char* knownTypes[] = {"integer", "string", "studio", "sound", "choices", "flags"};

    for (auto& type : knownTypes)
    {
        if (strcasecmp(keyType, type) == 0)
            return true;
    }
    return false;
}

void writefgd(std::ostream& stream, const Fgd& fgd, EditorType editorType)
{
    stream << "//generated by fgd2fgd\n\n";

    for (FgdClass* fgdClass : fgd.classes)
    {
        stream << fgdClassTypeToString(fgdClass->classType) << " ";

        if (!fgdClass->baseClasses.empty())
        {
            stream << "base(";
            bool first = true;
            for (auto baseClass : fgdClass->baseClasses)
            {
                if (!first)
                    stream << ", ";
                stream << baseClass;
                first = false;
            }
            stream << ") ";
        }

        if (fgdClass->colorSet)
        {
            stream << "color(" << (int)fgdClass->color.r << ' ' << (int)fgdClass->color.g << ' ' << (int)fgdClass->color.b << ") ";
        }

        if (fgdClass->sizeSet)
        {
            stream << "size(" << fgdClass->mins.toKeyvalueString(true, " ", " ", "") << ", " << fgdClass->maxs.toKeyvalueString(true, " ", " ", "") << ") ";
        }

        if (!fgdClass->model.empty())
        {
            if (editorType == EditorType::TrenchBroom)
            {
                stream << "model({ \"path\": \"" << fgdClass->model << "\", \"frame\": sequence, \"skin\": skin }) ";
            }
        }
        else if (fgdClass->isModel)
        {
            stream << "studio() ";
        }
        else if (fgdClass->isSprite)
        {
            stream << "sprite() ";
        }

        stream << "= " << fgdClass->name;
        if (fgdClass->classType != FGD_CLASS_BASE)
        {
            stream << " : \"" << fgdClass->name << "\"";
        }
        stream << "\n[\n";
        for (KeyvalueDef keyvalue : fgdClass->keyvalues)
        {
            stream << "\t" << keyvalue.name << "(";
            if (editorType == EditorType::NetRadiant)
            {
                if (isKnownTypeForAllEditors(keyvalue.valueType.c_str()))
                {
                    stream << keyvalue.valueType;
                }
                else
                {
                    stream << "string";
                }
            }
            else
            {
                stream << keyvalue.valueType;
            }
            stream << ")";

            if (keyvalue.name != "spawnflags")
            {
                stream <<  " : \"" << keyvalue.shortDescription << "\"";
            }
            if (!keyvalue.defaultValue.empty())
            {
                stream << " : ";
                if (keyvalue.iType == FGD_KEY_INTEGER || keyvalue.iType == FGD_KEY_CHOICES)
                    stream << keyvalue.defaultValue;
                else
                    stream << "\"" << keyvalue.defaultValue << "\"";
            }
            if (!keyvalue.choices.empty())
            {
                stream << " =\n";
                stream << "\t[\n";
                for (KeyvalueChoice& choice : keyvalue.choices)
                {
                    stream << "\t\t";
                    if (choice.isInteger)
                    {
                        stream << choice.ivalue;
                    }
                    else
                    {
                        stream << "\"" << choice.svalue << "\"";
                    }
                    stream << " : \"" << choice.name << "\"";
                    if (keyvalue.name == "spawnflags")
                    {
                        stream << " : " << choice.sdefvalue;
                    }
                    stream << "\n";
                }
                stream << "\t]";
            }
            stream << "\n";
        }
        stream << "]\n";
    }
}

int main(int argc, char** argv)
{
    const char* fileName = nullptr;
    EditorType editorType = EditorType::Hammer;

    for(int i=1; i<argc; ++i)
    {
        const char* arg = argv[i];
        if (strcmp(arg, "-type") == 0) {
            i++;
            if (i < argc) {
                if (strcmp(argv[i], "trenchbroom") == 0)
                {
                    editorType = EditorType::TrenchBroom;
                }
                else if (strcmp(argv[i], "netradiant") == 0)
                {
                    editorType = EditorType::NetRadiant;
                }
                else if (strcmp(argv[i], "hammer") == 0)
                {
                    editorType = EditorType::Hammer;
                }
                else
                {
                    fputs("Unknown editor type specified\n", stderr);
                    return EXIT_FAILURE;
                }
            } else {
                fputs("-type requires argument\n", stderr);
                return EXIT_FAILURE;
            }
        }
        else
        {
            fileName = argv[i];
        }
    }

    if (!fileName)
    {
        fputs("Expected an file path as argument!\n", stderr);
        return EXIT_FAILURE;
    }

    Fgd fgd(fileName);
    if (!fgd.parse())
    {
        fprintf(stderr, "Couldn't read %s\n", fileName);
        return 1;
    }
    writefgd(std::cout, fgd, editorType);
    return 0;
}
